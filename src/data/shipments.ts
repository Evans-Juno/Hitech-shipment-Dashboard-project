export const STAGES = [
  "Loaded from Departure Port",
  "Vessel on Sea",
  "Arrived to Nigerian Port",
  "Unloaded",
  "Under Customs Clearance",
  "Customs Completed",
] as const;
export type ArrivalStatus = (typeof STAGES)[number];

/** Colour group: sea = not yet in Nigeria, port = in Nigeria / customs, done = cleared */
export function stageTone(s: ArrivalStatus): "pending" | "transit" | "arrived" {
  const i = STAGES.indexOf(s);
  return i <= 1 ? "pending" : i <= 4 ? "transit" : "arrived";
}
